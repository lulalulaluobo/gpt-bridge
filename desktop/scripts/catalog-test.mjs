import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { readCatalog, updateCatalog, capabilityCall } from '../bridge/capabilities.mjs';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'bridge-catalog-'));
try {
  const root = path.join(temp, 'state'), skills = path.join(temp, 'skills'), bin = path.join(temp, 'bin');
  fs.mkdirSync(path.join(skills, 'office'), { recursive: true }); fs.mkdirSync(bin);
  const skill = path.join(skills, 'office', 'SKILL.md');
  fs.writeFileSync(skill, '---\nname: office\ndescription: >\n  Create documents\n  and slides\n---\nRead refs.md');
  fs.writeFileSync(path.join(skills, 'office', 'refs.md'), 'Reference SOP');
  const marker = path.join(temp, 'executed');
  fs.writeFileSync(path.join(bin, 'officecli'), `#!/bin/sh\ntouch '${marker}'`, { mode: 0o755 });
  const refresh = () => updateCatalog(root, 'refresh', { revision: readCatalog(root).revision, skillRoots: [skills], cliRoots: [bin] });
  let catalog = refresh();
  assert.equal(catalog.entries.length, 2); assert.equal(catalog.added, 2); assert(!fs.existsSync(marker));
  const sop = catalog.entries.find(e => e.kind === 'skill'), cli = catalog.entries.find(e => e.kind === 'cli');
  assert.equal(sop.description, 'Create documents and slides');
  const call = (name, args) => capabilityCall(root, name, args, false);
  assert.equal(call('search_capabilities', { query: 'slides' }).items[0].id, sop.id);
  assert.equal(call('search_capabilities', { query: '', limit: 1, kind: 'all' }).nextOffset, 1);
  assert.equal(call('search_capabilities', { query: '' }).total, 1);
  assert.equal(call('search_capabilities', { query: '', kind: 'cli' }).items[0].id, cli.id);
  assert.equal(call('read_skill', { id: sop.id, resource: 'refs.md' }).content, 'Reference SOP');
  assert.equal(call('read_skill', { id: sop.id }).executionReadiness.nativeToolsExposedByReading, false);
  assert.equal(call('search_capabilities', { query: 'no-match' }).taskRouting.version, 2);
  assert.equal(call('get_cli_info', { id: cli.id }).commandExecutionEnabled, false);
  assert(!fs.existsSync(marker));
  for (const resource of ['../outside.txt', '/etc/passwd']) assert.throws(() => call('read_skill', { id: sop.id, resource }));
  fs.writeFileSync(path.join(temp, 'outside.txt'), 'outside');
  fs.symlinkSync(path.join(temp, 'outside.txt'), path.join(skills, 'office', 'escape.md'));
  assert.throws(() => call('read_skill', { id: sop.id, resource: 'escape.md' }));
  assert.throws(() => call('search_capabilities', { query: '', limit: 100 }));
  assert.throws(() => call('read_skill', { id: 'unknown' }));
  catalog = updateCatalog(root, 'toggle', { revision: catalog.revision, id: sop.id, enabled: false });
  assert.equal(call('search_capabilities', { query: '', kind: 'skill' }).total, 0);
  assert.throws(() => call('read_skill', { id: sop.id }));
  const before = fs.readFileSync(path.join(root, 'capabilities.json'), 'utf8');
  assert.throws(() => updateCatalog(root, 'refresh', { revision: catalog.revision, skillRoots: ['/missing-catalog-root'], cliRoots: [] }));
  assert.equal(fs.readFileSync(path.join(root, 'capabilities.json'), 'utf8'), before);
  assert.throws(() => updateCatalog(root, 'toggle', { revision: 'stale', id: sop.id, enabled: true }));
  fs.appendFileSync(skill, '\nUpdated');
  catalog = refresh(); assert.equal(catalog.updated, 1); assert(catalog.disabledIDs.includes(sop.id));
  fs.unlinkSync(path.join(bin, 'officecli'));
  assert.equal(call('get_cli_info', { id: cli.id }).exists, false);
  catalog = refresh(); assert.equal(catalog.removed, 1);
  assert.equal(fs.statSync(path.join(root, 'capabilities.json')).mode & 0o777, 0o600);
  console.log('PASS: catalog discovery, dynamic refresh, disable, references, containment, stale writes, atomic failure and no execution');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
